-- Shift windows can include configured short breaks and lunch.
ALTER TYPE "AttendanceEventType" ADD VALUE IF NOT EXISTS 'LUNCH_START';
ALTER TYPE "AttendanceEventType" ADD VALUE IF NOT EXISTS 'LUNCH_END';

ALTER TABLE "Shift"
  ADD COLUMN IF NOT EXISTS "breakMinutes" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "lunchMinutes" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "breakIncluded" BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS "lunchIncluded" BOOLEAN NOT NULL DEFAULT true;

ALTER TABLE "Attendance"
  ADD COLUMN IF NOT EXISTS "lunchMinutes" INTEGER NOT NULL DEFAULT 0;